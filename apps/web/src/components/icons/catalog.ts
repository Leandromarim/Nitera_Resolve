export const ICONS: IconEntry[] = ICON_GROUPS.flatMap((group) => GROUPED[group].map(([name, Icon, label, keywords]) => ({ name, Icon, label, group, keywords })));
export const ICON_MAP: Record<string, IconEntry> = Object.fromEntries(ICONS.map((i) => [i.name, i]));
/** Ícone usado quando o nome salvo não existe no catálogo. */
export const FALLBACK_ICON = 'link';

const norm = (s: string) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase();

/** Busca por nome, grupo e palavras-chave em português, ignorando acentos. Todas as palavras precisam bater. */
export function searchIcons(query: string): IconEntry[] {
  const terms = norm(query).split(/\s+/).filter(Boolean);
  if (!terms.length) return ICONS;
  return ICONS.filter((i) => {
    const hay = norm(`${i.label} ${i.group} ${i.keywords} ${i.name}`);
    return terms.every((t) => hay.includes(t));
  });
}

